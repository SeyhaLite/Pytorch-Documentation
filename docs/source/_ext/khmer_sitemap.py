"""Generate sitemap.xml in the build output root.

Why a local extension instead of ``sphinx-sitemap``
--------------------------------------------------
Read the Docs sets ``READTHEDOCS_CANONICAL_URL`` (which conf.py assigns to
``html_baseurl``) to a URL that **already contains** the language and version
segments:

    https://pytorch-documentation.readthedocs.io/km/latest/

``sphinx-sitemap`` appends its own ``version`` and ``language`` segments to
``html_baseurl``, so with RTD's value it would emit
``/km/latest/km/latest/...``. Making it emit the right thing means setting both
to empty strings and relying on that staying correct across releases. Writing
the file directly is about the same amount of code, has no dependency, and the
URLs it produces are the ones we can assert on in a test.

Where the file ends up
----------------------
Sphinx writes it to the *build output* root, which Read the Docs serves under
``/<language>/<version>/``::

    https://pytorch-documentation.readthedocs.io/km/latest/sitemap.xml

That is the URL to submit in Google Search Console. RTD already serves its own
``/sitemap.xml`` at the domain root, but that one lists only version landing
pages -- a single ``<url>`` for this project -- so it does not expose the 22
lesson pages to crawlers.

Design choices
--------------
*   URL form is ``<docname>.html`` for every page including ``index``, matching
    the ``rel="canonical"`` links Sphinx already emits. Mixing ``/km/latest/``
    and ``/km/latest/index.html`` for the same page would hand Google two URLs
    for one document.
*   No ``<lastmod>``. The only available signal would be a file mtime, and git
    does not preserve mtimes -- every file in a fresh clone carries the checkout
    timestamp. Publishing that as a modification date would be a confident lie,
    and Google drops trust in ``lastmod`` when it is wrong.
*   No ``<changefreq>`` or ``<priority>``: Google ignores both.
*   The search page is excluded: it has no indexable content until JavaScript
    runs, so indexing it only adds a thin duplicate.
"""

from __future__ import annotations

import posixpath
from datetime import datetime, timezone
from pathlib import Path
from xml.sax.saxutils import escape

from sphinx.application import Sphinx
from sphinx.util import logging

__version__ = "1.0.0"

log = logging.getLogger(__name__)

# Used only when html_baseurl is empty (i.e. a local build with no
# READTHEDOCS_CANONICAL_URL), so that the generated sitemap still contains the
# real, resolvable production URLs and tests can assert on them.
DEFAULT_BASEURL = "https://pytorch-documentation.readthedocs.io/km/latest/"


def _normalise_base(base: str) -> str:
    """Guarantee exactly one trailing slash and an absolute http(s) URL."""
    base = base.strip()
    if not base:
        base = DEFAULT_BASEURL
    if not base.endswith("/"):
        base += "/"
    return base


def _page_url(base: str, docname: str) -> str:
    return base + posixpath.normpath(docname + ".html")


def write_sitemap(app: Sphinx, exception: Exception | None) -> None:
    """``build-finished`` hook: emit sitemap.xml into the output root."""
    if exception is not None:
        return                                  # build failed; write nothing
    if app.builder.name != "html":
        return                                  # only meaningful for HTML output

    base = _normalise_base(getattr(app.config, "html_baseurl", "") or "")
    exclude = set(app.config.sitemap_excluded_pages)

    docnames = sorted(set(app.builder.env.all_docs) - exclude)
    if not docnames:
        log.warning("sitemap: no pages to list")
        return

    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        f"  <!-- Generated by _ext/khmer_sitemap.py on {today}.",
        "       No <lastmod>: git does not preserve file mtimes, so the only",
        "       available date would be the checkout time, which is not a real",
        "       modification date. See the module docstring. -->",
    ]
    for docname in docnames:
        lines += [
            "  <url>",
            f"    <loc>{escape(_page_url(base, docname), {'&': '&amp;'})}</loc>",
            "  </url>",
        ]
    lines.append("</urlset>")

    out = Path(app.outdir) / "sitemap.xml"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("sitemap: wrote %d URLs to %s", len(docnames), out)


def setup(app: Sphinx) -> dict[str, object]:
    app.add_config_value(
        "sitemap_excluded_pages",
        # `search` renders nothing until JS runs; listing it would add a thin
        # duplicate of every page's title with no content behind it.
        ["search"],
        "html",
    )
    app.connect("build-finished", write_sitemap)
    return {
        "version": __version__,
        "parallel_read_safe": True,
        "parallel_write_safe": True,
    }
